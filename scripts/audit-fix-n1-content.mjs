import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const examNo = Number(process.argv[2]);
if (!Number.isInteger(examNo)) throw new Error("Pass one exam number");
const file = path.resolve(`data/exams/n1/original/n1-original-${String(examNo).padStart(2, "0")}.json`);
const exam = JSON.parse(await readFile(file, "utf8"));

function allQuestions() {
  return exam.sections.flatMap((section) => section.items.flatMap((item) => item.questions ?? [item]));
}

function question(id) {
  const found = allQuestions().find((item) => item.id === id);
  if (!found) throw new Error(`Question ${id} not found`);
  return found;
}

function choice(id, choiceId, text) {
  const found = question(id).choices.find((item) => item.id === choiceId);
  if (!found) throw new Error(`Choice ${id}/${choiceId} not found`);
  found.text = text;
}

function replaceOrder(id, sentenceBefore, sentenceAfter, fragments, correctOrder, starPosition) {
  const item = exam.sections.find((section) => section.id === "grammar").items.find((candidate) => candidate.id === id);
  if (!item || item.type !== "SENTENCE_ORDER") throw new Error(`Sentence order ${id} not found`);
  Object.assign(item, {
    sentenceBefore,
    sentenceAfter,
    fragments: fragments.map((text, index) => ({ id: index + 1, text })),
    correctOrder,
    starPosition,
    correctAnswer: correctOrder[starPosition - 1]
  });
}

